/**
 * Helper to replace template tokens like {name}, {id}, {done}
 */
export function formatCopy(text, vars = {}) {
  if (!text) return '';
  return text.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? `{${key}}`);
}
